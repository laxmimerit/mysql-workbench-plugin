// Writes MySQL's keyword, function and data type names into plugin/kgp-plugin.js,
// between the KEYWORDS:BEGIN and KEYWORDS:END markers.
// The lists are not ours: they come from sql-formatter's MySQL dialect, so an
// update of that package (npm install, then npm run keywords) brings new words.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mysql, expandPhrases } from 'sql-formatter';

const require = createRequire(import.meta.url);
const version = require('sql-formatter/package.json').version;
const t = mysql.tokenizerOptions;

// sql-formatter treats these as syntax in every dialect rather than listing them.
const keywords = new Set(['CASE', 'WHEN', 'THEN', 'ELSE', 'END']);
const phrases = [...t.reservedSelect, ...t.reservedClauses, ...t.reservedSetOperations, ...t.reservedJoins,
  ...(t.reservedKeywordPhrases ?? []), ...(t.reservedDataTypePhrases ?? [])];
for (const p of expandPhrases(phrases)) for (const w of p.split(/\s+/)) if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(w)) keywords.add(w.toUpperCase());
for (const k of t.reservedKeywords) keywords.add(k.toUpperCase());
const upper = xs => [...new Set((xs ?? []).map(x => x.toUpperCase()))].sort();

const lists = { k: [...keywords].sort(), f: upper(t.reservedFunctionNames), d: upper(t.reservedDataTypes) };
const block = `/* KEYWORDS:BEGIN generated by tools/gen-keywords.mjs from sql-formatter ${version} (MIT), MySQL dialect. Do not edit by hand. */\n`
  + ` const MYSQL_WORDS = { k: '${lists.k.join(' ')}', f: '${lists.f.join(' ')}', d: '${lists.d.join(' ')}' };\n`
  + ' /* KEYWORDS:END */';

const file = fileURLToPath(new URL('../plugin/kgp-plugin.js', import.meta.url));
const src = readFileSync(file, 'utf8');
const re = /\/\* KEYWORDS:BEGIN[\s\S]*?\/\* KEYWORDS:END \*\//;
if (!re.test(src)) throw new Error('KEYWORDS markers not found in plugin/kgp-plugin.js');
writeFileSync(file, src.replace(re, block));
console.log(`MySQL words from sql-formatter ${version}: ${lists.k.length} keywords, ${lists.f.length} functions, ${lists.d.length} data types`);
